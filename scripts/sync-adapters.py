#!/usr/bin/env python3
"""Sync and verify multi-harness thin adapters from the canonical .agents/ core."""

from __future__ import annotations

import argparse
import base64
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CANONICAL = ROOT / ".agents"

# Target harness directories mapped from canonical subdirectories
TARGETS: dict[str, list[Path]] = {
    "agents": [ROOT / ".claude" / "agents", ROOT / ".agent" / "agents"],
    "skills": [ROOT / ".claude" / "skills", ROOT / ".agent" / "skills"],
    "workflows": [ROOT / ".agent" / "workflows"],
}


CODEX_HOOKS = ROOT / ".codex" / "hooks.json"


def _normalized(path: Path) -> bytes:
    """Compare content independent of CRLF/LF so Windows checkouts do not report false drift."""
    return path.read_bytes().replace(b"\r\n", b"\n")


def write_text_lf(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def _powershell_encoded(subcommand: str) -> str:
    """PowerShell script passed via -EncodedCommand so cmd.exe and PowerShell never re-quote it."""
    script = (
        "[Console]::InputEncoding = [Text.UTF8Encoding]::new($false); "
        "$OutputEncoding = [Text.UTF8Encoding]::new($false); "
        "$root = (git rev-parse --show-toplevel); "
        f"$input | & (Join-Path $root 'scripts\\bin\\sdlc-hook.cmd') {subcommand} --platform codex; "
        "exit $LASTEXITCODE"
    )
    return base64.b64encode(script.encode("utf-16-le")).decode("ascii")


def _codex_handler(subcommand: str, timeout: int, background: bool = False) -> dict:
    handler = {
        "type": "command",
        "command": f'sh "$(git rev-parse --show-toplevel)/scripts/bin/sdlc-hook" {subcommand} --platform codex',
        "commandWindows": (
            "powershell.exe -NoProfile -NonInteractive -ExecutionPolicy Bypass -EncodedCommand "
            + _powershell_encoded(subcommand)
        ),
        "timeout": timeout,
    }
    if background:
        handler["async"] = True  # trace hooks must never slow down or block a tool call
    return handler


def render_codex_hooks() -> str:
    data = {
        "description": (
            "GENERATED by scripts/sync-adapters.py - do not edit. POSIX command runs scripts/bin/sdlc-hook via sh; "
            "commandWindows runs scripts\\bin\\sdlc-hook.cmd through PowerShell (-EncodedCommand avoids quoting "
            "differences between cmd.exe and PowerShell). Trust these hooks with /hooks after review."
        ),
        "hooks": {
            "SessionStart": [{"matcher": "startup|resume|clear", "hooks": [_codex_handler("session-start", 30)]}],
            "PreToolUse": [{"matcher": "Bash|apply_patch", "hooks": [_codex_handler("pretooluse", 30)]}],
            "UserPromptSubmit": [{"hooks": [_codex_handler("trace", 10, background=True)]}],
            "PostToolUse": [{"matcher": "Bash|apply_patch", "hooks": [_codex_handler("trace", 10, background=True)]}],
            "SubagentStart": [{"hooks": [_codex_handler("trace", 10, background=True)]}],
            "SubagentStop": [{"hooks": [_codex_handler("trace", 10, background=True)]}],
            "Stop": [{"hooks": [_codex_handler("trace", 10, background=True)]}],
            "SessionEnd": [{"hooks": [_codex_handler("trace", 3)]}],
        },
    }
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def iter_canonical_files(subdir: str) -> list[Path]:
    base = CANONICAL / subdir
    if not base.exists():
        return []
    return sorted(p for p in base.rglob("*") if p.is_file() and p.name != ".DS_Store")


def sync_adapters() -> int:
    copied = 0
    for subdir, destinations in TARGETS.items():
        src_base = CANONICAL / subdir
        src_files = iter_canonical_files(subdir)
        rel_set = {f.relative_to(src_base) for f in src_files}

        for dest_base in destinations:
            dest_base.mkdir(parents=True, exist_ok=True)
            # Remove stale files no longer present in canonical core
            for existing in list(dest_base.rglob("*")):
                if existing.is_file() and existing.relative_to(dest_base) not in rel_set:
                    existing.unlink()

            for src_file in src_files:
                rel = src_file.relative_to(src_base)
                dst_file = dest_base / rel
                dst_file.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(src_file, dst_file)
                copied += 1

    write_codex_index()
    write_text_lf(CODEX_HOOKS, render_codex_hooks())
    print(f"Synced {copied} adapter files from .agents/ and updated .codex/README.md + .codex/hooks.json")
    return 0


def check_parity() -> int:
    mismatches: list[str] = []
    for subdir, destinations in TARGETS.items():
        src_base = CANONICAL / subdir
        src_files = iter_canonical_files(subdir)
        rel_map = {f.relative_to(src_base): f for f in src_files}

        for dest_base in destinations:
            if not dest_base.exists():
                mismatches.append(f"Missing adapter directory: {dest_base.relative_to(ROOT)}")
                continue

            dest_files = {
                p.relative_to(dest_base): p
                for p in dest_base.rglob("*")
                if p.is_file() and p.name != ".DS_Store"
            }

            for rel, src_file in rel_map.items():
                if rel not in dest_files:
                    mismatches.append(f"Missing in {dest_base.relative_to(ROOT)}: {rel}")
                elif _normalized(src_file) != _normalized(dest_files[rel]):
                    mismatches.append(f"Content drift in {dest_base.relative_to(ROOT)}: {rel}")

            for rel in sorted(set(dest_files) - set(rel_map)):
                mismatches.append(f"Extra stale file in {dest_base.relative_to(ROOT)}: {rel}")

    if not CODEX_HOOKS.exists():
        mismatches.append("Missing generated file: .codex/hooks.json (run --sync)")
    elif _normalized(CODEX_HOOKS) != render_codex_hooks().encode("utf-8"):
        mismatches.append("Content drift in .codex/hooks.json (run --sync)")

    if mismatches:
        print("Adapter parity check FAILED:", file=sys.stderr)
        for item in mismatches:
            print(f"  - {item}", file=sys.stderr)
        return 1

    print("Adapter parity check PASSED (100% synced with .agents/)")
    return 0


def write_codex_index() -> None:
    agents = [p.stem for p in iter_canonical_files("agents")]
    skills = [p.parent.name for p in iter_canonical_files("skills") if p.name == "SKILL.md"]
    workflows = [p.stem for p in iter_canonical_files("workflows")]

    lines = [
        "# Codex Adapter Guidance",
        "",
        "Follow [AGENTS.md](../AGENTS.md) at the repository root.",
        "",
        "- Always start with [core-bootloader.md](../docs/workflow/core-bootloader.md) before modifying files.",
        "- Keep execution scoped to isolated tasks and verify changes with deterministic checks before handoff.",
        "",
        "## Canonical Agents (`.agents/agents/`)",
        *[f"- `{name}`" for name in agents],
        "",
        "## Canonical Skills (`.agents/skills/`)",
        *[f"- `{name}`" for name in skills],
        "",
        "## Canonical Workflows (`.agents/workflows/`)",
        *[f"- `{name}`" for name in workflows],
        "",
    ]
    write_text_lf(ROOT / ".codex" / "README.md", "\n".join(lines))


def main() -> int:
    parser = argparse.ArgumentParser(description="Sync or check .agents/ harness adapters.")
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--sync", action="store_true", help="Mirror .agents/ to host adapters.")
    group.add_argument("--check", action="store_true", help="Verify 100% parity with .agents/.")
    args = parser.parse_args()

    return sync_adapters() if args.sync else check_parity()


if __name__ == "__main__":
    raise SystemExit(main())
